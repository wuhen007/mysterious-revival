def G(
    gid: str,
    name: str,
    grade: str,
    stats: tuple[int, int, int, int],
    capture: tuple[float, float],
    skill: tuple[str, str, float, int],
    rule: tuple[str, str, str, list[str], list[str], str | None],
    behavior: tuple[str, dict[str, Any]] | None = None,
    desc: str = "",
    starter: int = 1,
) -> dict[str, Any]:
    hp, atk, df, spd = stats
    threshold, difficulty = capture
    skill_id, skill_name, power, cooldown = skill
    rule_id, rule_desc, counter_method, clues, counteractions, flag = rule
    record: dict[str, Any] = {
        "id": gid,
        "schema_version": 1,
        "name": name,
        "description": desc,
        "grade": grade,
        "stats": {"hp": hp, "attack": atk, "defense": df, "speed": spd},
        "capture_threshold": threshold,
        "capture_difficulty": difficulty,
        "base_loyalty": 50,
        "starter_weight": starter,
        "skills": [
            {
                "id": skill_id,
                "name": skill_name,
                "type": "attack",
                "power": power,
                "cooldown_turns": cooldown,
            }
        ],
        "rules": [
            {
                "id": rule_id,
                "description": rule_desc,
                "clues": clues,
                "reveal_after": max(1, len(clues)),
                "discovery_san_cost": 5,
                "counter_method": counter_method,
                "counteractions": counteractions,
            }
        ],
        "behavior": {"kind": "brute", "target_strategy": "weakest", "attack_multiplier": 1.0},
    }
    if flag:
        record["rules"][0]["story_flag_on_counteraction"] = flag
    if behavior:
        kind, extra = behavior
        record["behavior"].update({"kind": kind, **extra})
    return record


